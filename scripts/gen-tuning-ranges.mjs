// Emit servers/authorlink/tuningRanges.generated.mjs from the TypeScript
// schema, so a relay host (plain Node, or a Cloudflare Worker) can enforce
// bounds without importing the app.
//
// Generated rather than hand-written for the same reason the allowlist is
// derived: `config/params.ts` and `ui/Inspector.ts` are the sources of truth
// for what a dial is and how far it goes, and a second hand-maintained copy
// would go stale the first time someone adds one. `--check` fails when the
// committed file no longer matches, so CI catches the drift instead of a
// hosted room silently refusing a legitimate change.
//
// Usage: node scripts/gen-tuning-ranges.mjs [--check]
import { build } from 'esbuild';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = fileURLToPath(new URL('..', import.meta.url));
const outPath = join(repoRoot, 'servers', 'authorlink', 'tuningRanges.generated.mjs');
const check = process.argv.includes('--check');

const entry = `
export { listTuningPaths } from '@/net/tuningPatch';
export { tuningRangeFor } from '@/config/tuningRanges';
`;

const tmp = await mkdtemp(join(tmpdir(), 'ad-ranges-'));
try {
  const entryPath = join(tmp, 'entry.ts');
  await writeFile(entryPath, entry, 'utf8');
  const bundlePath = join(tmp, 'bundle.mjs');
  await build({
    entryPoints: [entryPath],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    outfile: bundlePath,
    logLevel: 'silent',
    alias: { '@': join(repoRoot, 'src') },
    // The schema modules are pure, but they sit in files that also reference
    // browser globals at type level; neutral platform + these shims keep the
    // bundle importable under plain Node.
    define: { 'import.meta.env.DEV': 'false' },
  });

  const mod = await import(pathToFileURL(bundlePath).href);
  const paths = mod.listTuningPaths();
  const table = {};
  let bounded = 0;
  for (const path of paths) {
    const range = mod.tuningRangeFor(path);
    if (!range) continue;
    table[path] = range.step === undefined ? { min: range.min, max: range.max } : range;
    bounded++;
  }

  const body =
    `// GENERATED by scripts/gen-tuning-ranges.mjs — do not edit.\n` +
    `// Source: src/config/tuningRanges.ts (+ ui/Inspector paramSliderSpec, config/gen).\n` +
    `// ${bounded} of ${paths.length} tuning paths carry declared bounds; a strict\n` +
    `// (hosted) room refuses the rest rather than clamping them silently.\n\n` +
    `export const TUNING_RANGES = ${JSON.stringify(table, null, 2)};\n\n` +
    `export function tuningRangeFor(path) {\n` +
    `  return Object.prototype.hasOwnProperty.call(TUNING_RANGES, path) ? TUNING_RANGES[path] : null;\n` +
    `}\n`;

  if (check) {
    if (!existsSync(outPath)) {
      console.error(`missing ${outPath}; run node scripts/gen-tuning-ranges.mjs`);
      process.exit(1);
    }
    const current = await readFile(outPath, 'utf8');
    if (current.replace(/\r\n/g, '\n') !== body) {
      console.error('tuningRanges.generated.mjs is stale; run node scripts/gen-tuning-ranges.mjs');
      process.exit(1);
    }
    console.log(`tuning ranges up to date (${bounded}/${paths.length} paths bounded)`);
  } else {
    await writeFile(outPath, body, 'utf8');
    console.log(`wrote ${outPath} (${bounded}/${paths.length} paths bounded)`);
  }
} finally {
  await rm(tmp, { recursive: true, force: true });
}
