// Offline only. Key stays in the ElevenLabs client's process memory.
// ELEVENLABS_API_KEY_FILE points to a user-owned file; never copy it here.
import { mkdirSync, writeFileSync, statSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { ARENA_MUSIC_CUES, ARENA_MUSIC_MODEL } from './arena-music-prompts.mjs';
process.env.AUDIO_LOG_NAME = 'generation-log.arena-music.jsonl';
const { music, Budget, measure } = await import('./elevenlabs.mjs');
const budget = new Budget(6500);
const output = 'public/audio/music/arena';
mkdirSync(output, { recursive: true });
function ffmpeg(args) {
  const r = spawnSync('ffmpeg', ['-hide_banner', '-nostats', ...args], { encoding: 'utf8', maxBuffer: 32 << 20 });
  if (r.status !== 0) throw new Error('Arena mastering failed');
  return r.stderr;
}
const rows = [], evidence = [];
try {
  for (const cue of ARENA_MUSIC_CUES) {
    console.log(`Composing ${cue.id} (${cue.seconds}s)...`);
    const take = await music({ prompt: cue.prompt, lengthMs: cue.seconds * 1000, modelId: ARENA_MUSIC_MODEL, forceInstrumental: true, outputFormat: 'mp3_44100_192' }, budget);
    const file = `${output}/${cue.id}.mp3`;
    // Preserve bar duration. Overlap the 40 ms following the final bar with the
    // first 40 ms, then put that seam at the end of the file. Native media looping
    // keeps the pulse without a 250 ms main-thread timer starting a second beat.
    const period = cue.loop ? cue.loopBars * 4 * 60 / cue.bpm : 0;
    const start = cue.loopStart ?? 0, end = start + period, seam = 0.04;
    const edit = cue.loop
      ? `[0:a]asplit=3[a][b][c];[a]atrim=start=${start + seam}:end=${end},asetpts=PTS-STARTPTS[body];[b]atrim=start=${end}:end=${end + seam},asetpts=PTS-STARTPTS[tail];[c]atrim=start=${start}:end=${start + seam},asetpts=PTS-STARTPTS[head];[tail][head]acrossfade=d=${seam}:c1=tri:c2=tri[join];[body][join]concat=n=2:v=0:a=1`
      : '[0:a]silenceremove=start_periods=1:start_threshold=-60dB:start_silence=0.025';
    const first = ffmpeg(['-i', take.file, '-filter_complex', `${edit},loudnorm=I=-16:TP=-2:LRA=18:print_format=json[out]`, '-map', '[out]', '-f', 'null', '-']);
    const m = JSON.parse(first.slice(first.lastIndexOf('{'), first.lastIndexOf('}') + 1));
    const norm = `loudnorm=I=-16:TP=-2:LRA=18:measured_I=${m.input_i}:measured_TP=${m.input_tp}:measured_LRA=${m.input_lra}:measured_thresh=${m.input_thresh}:offset=${m.target_offset}:linear=true`;
    ffmpeg(['-y', '-i', take.file, '-filter_complex', `${edit},${norm}[out]`, '-map', '[out]', '-ar', '44100', '-ac', '2', '-codec:a', 'libmp3lame', '-q:a', '4', file]);
    const measured = measure(file);
    const silence = ffmpeg(['-i', file, '-af', 'silencedetect=noise=-48dB:d=0.15', '-f', 'null', '-']);
    const starts = [...silence.matchAll(/silence_start: ([\d.]+)/g)].map(m => Number(m[1]));
    const last = starts.at(-1);
    const tailSec = last !== undefined && measured.duration - last < 5 ? Math.round((measured.duration - last) * 100) / 100 : 0;
    rows.push({ id: cue.id, url: `audio/music/arena/${cue.id}.mp3`, label: cue.label, group: 'Score · Arena', role: 'arena', floor: null, loop: cue.loop, gaplessLoop: cue.loop, key: cue.key, bpm: cue.bpm, seconds: measured.duration, headSec: 0, tailSec, lufs: measured.lufs, bytes: statSync(file).size, summary: cue.prompt });
    evidence.push({ id: cue.id, model: ARENA_MUSIC_MODEL, songId: take.meta.songId, cacheKey: take.key, sha256: createHash('sha256').update(readFileSync(file)).digest('hex'), ...measured, tailSec, loopEdit: cue.loop ? { start, bars: cue.loopBars, period, seam } : null, bytes: statSync(file).size });
    console.log(`${cue.id}: ${measured.duration}s, ${measured.lufs} LUFS, ${measured.truePeak} dBTP`);
  }
  writeFileSync('src/content/audio/arenaScore.generated.ts', `// Generated by scripts/audio/gen-arena-music.mjs.\nimport type { ScoreTrack } from '@/content/audio/scoreTypes';\nexport const ARENA_SCORE_TRACKS: readonly ScoreTrack[] = ${JSON.stringify(rows, null, 2)};\n`);
  writeFileSync('scripts/audio/arena-music-report.json', JSON.stringify(evidence, null, 2) + '\n');
} catch (e) {
  // Never dump request/header objects. The client error only carries server response text.
  console.error(String(e.message).replace(/sk_[A-Za-z0-9]+/g, '[redacted]'));
  process.exitCode = 1;
}
