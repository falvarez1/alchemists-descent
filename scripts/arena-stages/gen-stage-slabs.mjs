// Collect every baked stage slab (public/assets/arena/<stage>/<slab>.json, made by bake-slab.mjs) into the typed module
// src/content/arena/stageSlabs.generated.ts. Collision must not wait for an image: the masks are code, the colours are art.
// Usage: node scripts/arena-stages/gen-stage-slabs.mjs [--check]
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join } from 'node:path';

const root = 'public/assets/arena';
const slabs = [];
for (const stage of readdirSync(root).sort()) {
  const dir = join(root, stage);
  if (!statSync(dir).isDirectory()) continue;
  for (const file of readdirSync(dir).sort()) {
    if (!file.endsWith('.json') || file === 'stage.json') continue;
    const j = JSON.parse(readFileSync(join(dir, file), 'utf8'));
    if (!Array.isArray(j.runs)) continue;
    slabs.push(j);
  }
}
const lines = [
  '// GENERATED by scripts/arena-stages/gen-stage-slabs.mjs from public/assets/arena/<stage>/<slab>.json. Do not edit.',
  '// Each slab: its width and depth in cells, the solid hull as row runs [x0, x1, x0, x1, ...] (inclusive, slab-relative),',
  '// the hangings drawn as presentation-resolution decor (never solid), and the lantern glass cells (real light, soft).',
  'export interface StageSlabArt {',
  '  readonly width: number;',
  '  readonly depth: number;',
  '  readonly runs: readonly (readonly number[])[];',
  '  readonly decor: { readonly file: string; readonly x: number; readonly y: number; readonly w: number; readonly h: number } | null;',
  '  readonly glass: readonly (readonly [number, number])[];',
  '  /** The hull face at presentation (half-cell) resolution, drawn over surviving cells by close framings. */',
  '  readonly fine: string | null;',
  '}',
  '',
  'export const STAGE_SLAB_ART: Readonly<Record<string, StageSlabArt>> = {',
];
for (const s of slabs) {
  lines.push(`  '${s.stage}/${s.slab}': {`);
  lines.push(`    width: ${s.width}, depth: ${s.depth},`);
  lines.push(`    runs: [${s.runs.map(r => `[${r.join(',')}]`).join(',')}],`);
  lines.push(`    decor: ${s.decor ? JSON.stringify(s.decor).replace(/"(\w+)":/g, '$1: ').replace(/"/g, "'") : 'null'},`);
  lines.push(`    glass: [${s.glass.map(([x, y]) => `[${x},${y}]`).join(',')}],`);
  lines.push(`    fine: ${s.fine ? `'${s.fine}'` : 'null'},`);
  lines.push('  },');
}
lines.push('};', '');
const out = 'src/content/arena/stageSlabs.generated.ts';
const text = lines.join('\n');
if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (current !== text) { console.error(`${out} is stale: run node scripts/arena-stages/gen-stage-slabs.mjs`); process.exit(1); }
  console.log(`${out} is current (${slabs.length} slabs)`);
} else {
  writeFileSync(out, text);
  console.log(`${out}: ${slabs.length} slabs (${slabs.map(s => `${s.stage}/${s.slab}`).join(', ')})`);
}
